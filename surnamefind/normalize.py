"""Нормализация дореформенной орфографии и OCR-артефактов."""

# Побуквенные замены: дореформенные литеры -> современные
CHAR_MAP = {
    "ѣ": "е", "Ѣ": "е",   # ять
    "і": "и", "І": "и",   # и десятеричное
    "ї": "и", "Ї": "и",
    "ѳ": "ф", "Ѳ": "ф",   # фита
    "ѵ": "и", "Ѵ": "и",   # ижица
    "ѕ": "з", "Ѕ": "з",   # зело
    "ѧ": "я", "Ѧ": "я",
    "ѫ": "у", "Ѫ": "у",
    "ё": "е", "Ё": "е",
    "й": "и", "Й": "и",   # й/и не различаем: OCR путает надстрочный знак
    "ь": "",              # мягкий знак съедаем — OCR путает ь/ъ/ы
    "ъ": "",              # твёрдый знак съедаем везде, не только в конце
}

# Латиница, которую OCR подсовывает вместо кириллицы (одинаковые глифы)
LATIN_LOOKALIKE = {
    "a": "а", "e": "е", "o": "о", "p": "р", "c": "с", "y": "у", "x": "х",
    "A": "а", "B": "в", "E": "е", "K": "к", "M": "м", "H": "н", "O": "о",
    "P": "р", "C": "с", "T": "т", "X": "х", "y": "у", "n": "п", "u": "и",
}


def normalize(word: str) -> str:
    """Приводит слово к сравнимому виду.

    Не пытается быть обратимой: задача — свести все варианты написания
    одной фамилии к одной строке. 'Кузнѣцовъ', 'Кузнецов', 'КУЗНЕЦОВЪ'
    -> 'кузнецов'.
    """
    out = []
    for ch in word:
        ch = LATIN_LOOKALIKE.get(ch, ch)
        ch = CHAR_MAP.get(ch, ch)
        out.append(ch)
    return "".join(out).lower()


def dehyphenate(text: str) -> str:
    """Склеивает слова, разорванные переносом на границе строк.

    В сканах это массово: 'Кузне-\nцовъ'. Без этого фамилия просто
    не существует в тексте как единый токен.
    """
    import re
    return re.sub(r"[-‐‑–­]\s*\n\s*", "", text)


# Литеры, отменённые реформой 1918 г.: OCR-модели, обученные на
# современной кириллице, читают их случайным образом.
PREREFORM = set("ѣ�ѢіІїЇѳѲѵѴѕЅѧѦѫѪ")


def normalize_marked(word: str):
    """normalize + позиции в результате, пришедшие из дореформенных литер.

    Нужно, чтобы штрафовать искажения именно там, где они ожидаемы,
    не ослабляя сравнение по остальным буквам.
    """
    out, fragile = [], []
    for ch in word:
        if ch in PREREFORM:
            fragile.append(len(out))
        src = LATIN_LOOKALIKE.get(ch, ch)
        mapped = CHAR_MAP.get(src, src)
        if mapped:
            out.append(mapped.lower())
        elif fragile and fragile[-1] == len(out):
            fragile.pop()          # литера схлопнулась в пустоту (ъ/ь)
    return "".join(out), fragile
